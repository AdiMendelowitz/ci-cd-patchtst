"""Real-data analysis: ETTh1, ECL, and dataset correlation characterisation.

Reads
-----
results/results_etth1.csv             Required. ETTh1 CI vs CD per-seed,
    matched-budget protocol (batch=32 both modes, warmup=10 both, min_epochs=15),
    five seeds {42, 123, 456, 789, 1011}.
    Required columns: mode, pred_len, seed, test_mse, best_epoch.
    Optional budget columns: steps_per_epoch, total_steps_to_best.

results/results_ecl.csv        Optional. ECL per-seed results, CI and CD.
    Required columns: mode, pred_len, seed, test_mse.
    If an arch_version column is present, every row must carry the value 2;
    the script raises otherwise. Modes, horizons, and seeds are taken from the
    file rather than assumed, and the summary and figure adapt to what is
    present. If absent, the ECL panel is omitted and the figure is incomplete
    for submission.

results/realdata_corr_summary.csv         Optional. Pre-computed per-dataset
    lag-0 and lag-structure summary. Produced by
    src/analysis/measure_lag_structure.py, which must be run first; this
    script does not compute correlation statistics itself, only reports and
    verifies them.
    Required columns: dataset, lag0_mean_abs_r, lag0_median_abs_r,
    mean_max_over_lags, pct_pairs_gain_ge_5pct_from_lags.

results/realdata_lag_summary.csv          Optional. Mean abs cross-correlation
    at each lag per dataset, from the same upstream script. Required columns:
    dataset, lag, mean_abs_r.

Writes
------
paper/figures/real_data.png
    Left panel: ETTh1 CI vs CD bar chart across horizons {96, 192, 336, 720}.
    Right panel (if ECL available): ECL bar chart over the modes and horizons
    present in the file. Error bars are drawn only where a group has two or
    more seeds; single-seed groups are plotted without error bars and the
    panel title states the seeds used.

Console
-------
ETTh1 ratio table; per-horizon paired CD-CI differences with 95% t-CIs;
budget-match verification table (CD/CI steps_per_epoch ratio equals 1.0);
ECL summary; dataset correlation characterisation (descriptive, with explicit
heuristic disclaimer) with an oracle check against the values quoted in
main.tex Section 3.2.

Statistical notes
-----------------
ETTh1 uses a budget matched across modes: batch size 32 and warmup_epochs 10 for both CI and CD, with a 15-epoch
minimum before early stopping. CI and CD therefore run an identical number of gradient updates per epoch at each
horizon, so neither the step count nor the warmup schedule can account for any CI-CD difference. The earlier
confounded run (ci_cd_etth1_raw_with_budget.csv: CI batch 128 vs CD batch 32, CI warmup 10 vs CD warmup 2) is retired.

With n=5 seeds per horizon (df=4, t-critical=2.776) the paired CD-CI differences are tested per horizon and pooled.
CD never attains a significant advantage; CI is significantly better at H=96 and H=720, and the pooled difference
favours CI. The step-count table below verifies the budget match (CD/CI steps_per_epoch ratio equals 1.0) rather than
documenting an asymmetry.

ECL results are descriptive. Confidence intervals and significance tests are
reported only for groups with at least two seeds; a single-seed group is
reported as point estimates with the seed identified.

Correlation summary provenance: realdata_corr_summary.csv is regenerated by
src/analysis/measure_lag_structure.py whenever the underlying data split
changes (in particular, the ECL train_rows value must match the paper's
proportional 60/20/20 split, currently 15,813). This script cross-checks the
loaded summary against a pinned oracle (_ORACLE_CORR below) and reports
PASS/FAIL per dataset rather than trusting an unreviewed run. Before the
oracle has been pinned for the first time, it prints the computed values as
UNVERIFIED and does not fail the run; a human must review those values
against main.tex and pin them before the corresponding paper numbers are
treated as confirmed.

Usage
-----
uv run src/analysis/analyze_realdata.py [path/to/results_etth1.csv]
Run from the repository root; all paths resolve relative to it.
"""

